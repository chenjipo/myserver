  \`ntype\` varchar(8) CHARACTER SET utf8 DEFAULT '' COMMENT '网络类型(Network)',
  \`nname\` varchar(32) CHARACTER SET utf8 DEFAULT '' COMMENT '网络名称',
  \`ip\` varchar(15) CHARACTER SET utf8 NOT NULL DEFAULT '' COMMENT '客户端IP',
  \`continent\` varchar(32) CHARACTER SET utf8 DEFAULT '' COMMENT '大洲',
  \`country\` varchar(32) CHARACTER SET utf8 DEFAULT '' COMMENT '国家',
  \`province\` varchar(32) CHARACTER SET utf8 DEFAULT '' COMMENT '省份',
  \`city\` varchar(32) CHARACTER SET utf8 DEFAULT '' COMMENT '城市',
  \`ymd\` int(8) NOT NULL COMMENT '年月日',
  \`h\` int(10) DEFAULT '0' COMMENT '年月日小时(2015070815)',
  \`atime\` int(11) DEFAULT '0' COMMENT '请求时间',
  PRIMARY KEY (\`id\`),
  KEY \`duid\` (\`duid\`) USING BTREE,
  KEY \`ymd\` (\`ymd\`,\`appid\`,\`cid\`,\`refer\`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='登录日志表';"